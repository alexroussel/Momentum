//! Tauri glue for Momentum: window setup, typed commands, persistence wiring.
//! Domain logic lives in `momentum-core`; persistence in `momentum-store`.

mod commands;
mod smoke;
mod state;
mod window;

use state::AppState;
use tauri::Manager;

/// Builds the typed command/event registry shared by the app and the bindings exporter.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new().commands(tauri_specta::collect_commands![
        commands::get_app_info,
        commands::get_preferences,
        commands::set_preferences,
        commands::list_categories,
        commands::frontend_ready,
    ])
}

pub fn run() {
    let smoke_test = std::env::args().any(|a| a == "--smoke-test");
    let builder = specta_builder();

    tauri::Builder::default()
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let state = AppState::init(app.handle(), smoke_test)?;
            app.manage(state);
            if let Some(main) = app.get_webview_window("main") {
                window::apply_platform_style(&main);
            }
            if smoke_test {
                smoke::arm_timeout(app.handle().clone());
            }
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running Momentum");
}

#[cfg(test)]
mod tests {
    /// Regenerates `src/bindings.ts`. CI runs this and fails if the file changed (ADR-005).
    #[test]
    fn export_bindings() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings.ts");
        super::specta_builder()
            .export(
                specta_typescript::Typescript::default()
                    .header("// @ts-nocheck\n// Generated by tauri-specta. Do not edit.\n"),
                path,
            )
            .expect("failed to export TypeScript bindings");
    }
}
